INSERT INTO batches (medicine_id, batch_number, expiry_date, quantity, received_date)
SELECT m.medicine_id,
       'B' || to_char(current_date + d.days, 'YYMM') || chr(64 + d.n),
       current_date + d.days,
       d.qty,
       current_date - 120 + d.n
FROM medicines m
CROSS JOIN LATERAL (
    VALUES (1, 30 + (m.medicine_id * 7) % 40, 20 + (m.medicine_id * 13) % 30),
           (2, 110 + (m.medicine_id * 11) % 50, 40 + (m.medicine_id * 17) % 30),
           (3, 230 + (m.medicine_id * 5) % 60, 30 + (m.medicine_id * 3) % 30),
           (4, 360 + (m.medicine_id * 9) % 80, 20 + (m.medicine_id * 19) % 50),
           (5, 520 + (m.medicine_id * 3) % 90, 50 + (m.medicine_id * 23) % 20)
) AS d(n, days, qty)
WHERE d.n <= 3 + m.medicine_id % 3;

UPDATE batches SET quantity = 36 WHERE batch_number LIKE 'B%A' AND medicine_id = 1;

