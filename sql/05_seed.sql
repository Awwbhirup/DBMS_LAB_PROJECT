INSERT INTO dispensing_events (medicine_id, batch_id, prescription_id, event_type, quantity_changed, performed_by, event_timestamp)
SELECT b.medicine_id,
       b.batch_id,
       NULL,
       'DISPENSE',
       -(1 + (g * 7) % 20),
       1 + g % 3,
       now() - ((g % 60) || ' days')::interval - ((g * 37 % 600) || ' minutes')::interval
FROM generate_series(1, 3000) AS g
JOIN LATERAL (
    SELECT batch_id, medicine_id
    FROM batches
    WHERE medicine_id = 1 + (g * g) % 44
      AND quantity > 0
      AND batch_number NOT LIKE 'H%'
    ORDER BY expiry_date
    LIMIT 1
) b ON true;

INSERT INTO dispensing_events (medicine_id, batch_id, prescription_id, event_type, quantity_changed, performed_by, event_timestamp)
SELECT b.medicine_id,
       b.batch_id,
       NULL,
       'RECEIPT',
       b.quantity + COALESCE((SELECT -SUM(e.quantity_changed) FROM dispensing_events e WHERE e.batch_id = b.batch_id), 0),
       4,
       b.received_date::timestamptz + interval '10 hours'
FROM batches b
WHERE b.quantity > 0;

